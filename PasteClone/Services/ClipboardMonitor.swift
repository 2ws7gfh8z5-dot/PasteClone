import Foundation
import AppKit

class ClipboardMonitor {
    private var timer: Timer?
    private var lastChangeCount: Int = -1
    var onChange: ((Int, ClipboardItem?) -> Void)?

    static var isPaused: Bool {
        get { UserDefaults.standard.bool(forKey: "monitorPaused") }
        set { UserDefaults.standard.set(newValue, forKey: "monitorPaused") }
    }

    static var ignoreNext: Bool {
        get { UserDefaults.standard.bool(forKey: "monitorIgnoreNext") }
        set { UserDefaults.standard.set(newValue, forKey: "monitorIgnoreNext") }
    }

    func start() {
        lastChangeCount = NSPasteboard.general.changeCount
        UserDefaults.standard.register(defaults: ["pollIntervalMs": 400])
        let interval = Double(min(max(UserDefaults.standard.integer(forKey: "pollIntervalMs"), 100), 2000)) / 1000
        timer = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(timer!, forMode: .common)
    }

    func stop() { timer?.invalidate(); timer = nil }

    private static let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("Pasteboard generator type"),
        NSPasteboard.PasteboardType("net.antelle.keeweb"),
    ]

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        if Self.isPaused { return }
        if Self.ignoreNext { Self.ignoreNext = false; return }
        if pb.types?.contains(where: { Self.sensitiveTypes.contains($0) }) == true { return }
        let sourceApp = NSWorkspace.shared.frontmostApplication
        guard !PrivacyRules.excludes(bundleIdentifier: sourceApp?.bundleIdentifier) else { return }
        onChange?(lastChangeCount, read(pb, sourceApp: sourceApp))
    }

    private func makeItem(type: ClipboardItemType, sourceApp: NSRunningApplication?, textContent: String? = nil, rtfData: Data? = nil, richTextType: String? = nil, imageData: Data? = nil, fileURLs: [URL]? = nil, colorData: Data? = nil) -> ClipboardItem {
        ClipboardItem(type: type, textContent: textContent, rtfData: rtfData, richTextType: richTextType, imageData: imageData,
                      fileURLs: fileURLs, colorData: colorData, sourceAppName: sourceApp?.localizedName,
                      sourceAppBundleID: sourceApp?.bundleIdentifier)
    }

    private func read(_ pb: NSPasteboard, sourceApp: NSRunningApplication?) -> ClipboardItem? {
        // Image
        if pb.availableType(from: [.tiff, .png]) != nil,
           let img = NSImage(pasteboard: pb),
           let tiff = img.tiffRepresentation,
           var rep = NSBitmapImageRep(data: tiff) {
            let maxEdge = 2048.0 // ponytail: fixed 2048px cap; expose as a preference if anyone asks
            let long = Double(max(rep.pixelsWide, rep.pixelsHigh))
            if long > maxEdge {
                let s = maxEdge / long
                let target = NSSize(width: Double(rep.pixelsWide) * s, height: Double(rep.pixelsHigh) * s)
                let scaled = NSImage(size: target)
                scaled.lockFocus()
                NSGraphicsContext.current?.imageInterpolation = .high
                img.draw(in: NSRect(origin: .zero, size: target))
                scaled.unlockFocus()
                if let st = scaled.tiffRepresentation, let srep = NSBitmapImageRep(data: st) { rep = srep }
            }
            if let png = rep.representation(using: .png, properties: [:]) {
                return makeItem(type: .image, sourceApp: sourceApp, imageData: png)
            }
        }
        // File URLs
        if let items = pb.readObjects(forClasses: [NSURL.self], options: nil) as? [URL], !items.isEmpty {
            return makeItem(type: .file, sourceApp: sourceApp, fileURLs: Array(items.prefix(50)))
        }
        // RTF
        if let d = pb.data(forType: .rtf) {
            let plain = try? NSAttributedString(data: d,
                options: [.documentType: NSAttributedString.DocumentType.rtf],
                documentAttributes: nil)
            if d.count > 2_000_000 { return makeItem(type: .text, sourceApp: sourceApp, textContent: plain?.string) }
            return makeItem(type: .rtf, sourceApp: sourceApp, textContent: plain?.string, rtfData: d, richTextType: NSPasteboard.PasteboardType.rtf.rawValue)
        }
        // RTFD
        if let d = pb.data(forType: .rtfd) {
            let plain = try? NSAttributedString(data: d,
                options: [.documentType: NSAttributedString.DocumentType.rtfd],
                documentAttributes: nil)
            if d.count > 2_000_000 { return makeItem(type: .text, sourceApp: sourceApp, textContent: plain?.string) }
            return makeItem(type: .rtf, sourceApp: sourceApp, textContent: plain?.string, rtfData: d, richTextType: NSPasteboard.PasteboardType.rtfd.rawValue)
        }
        // Native macOS color objects
        if let color = (pb.readObjects(forClasses: [NSColor.self]) as? [NSColor])?.first,
           let data = try? NSKeyedArchiver.archivedData(withRootObject: color, requiringSecureCoding: true) {
            return makeItem(type: .color, sourceApp: sourceApp, colorData: data)
        }
        // Plain text
        if let txt = pb.string(forType: .string), !txt.isEmpty {
            guard txt.utf8.count <= 2_000_000 else { return nil }
            return makeItem(type: .text, sourceApp: sourceApp, textContent: txt)
        }
        return nil
    }
}
